LibMCDriver_ScannerEmulatorResult libmcdriver_scanneremulator_createdriver(const char * pName, const char * pType, LibMCEnv_DriverEnvironment pDriverEnvironment, LibMCDriver_ScannerEmulator_Driver * pInstance)
{
	IBase* pIBaseClass = nullptr;

	try {
		if (pName == nullptr)
			throw ELibMCDriver_ScannerEmulatorInterfaceException (LIBMCDRIVER_SCANNEREMULATOR_ERROR_INVALIDPARAM);
		if (pType == nullptr)
			throw ELibMCDriver_ScannerEmulatorInterfaceException (LIBMCDRIVER_SCANNEREMULATOR_ERROR_INVALIDPARAM);
		if (pInstance == nullptr)
			throw ELibMCDriver_ScannerEmulatorInterfaceException (LIBMCDRIVER_SCANNEREMULATOR_ERROR_INVALIDPARAM);
		std::string sName(pName);
		std::string sType(pType);
		LibMCEnv::PDriverEnvironment pIDriverEnvironment = std::make_shared<LibMCEnv::CDriverEnvironment>(CWrapper::sPLibMCEnvWrapper.get(), pDriverEnvironment);
		CWrapper::sPLibMCEnvWrapper->AcquireInstance(pIDriverEnvironment.get());
		if (!pIDriverEnvironment)
			throw ELibMCDriver_ScannerEmulatorInterfaceException (LIBMCDRIVER_SCANNEREMULATOR_ERROR_INVALIDCAST);
		
		IBase* pBaseInstance(nullptr);
		pBaseInstance = CWrapper::CreateDriver(sName, sType, pIDriverEnvironment);

		*pInstance = (IBase*)(pBaseInstance);
		return LIBMCDRIVER_SCANNEREMULATOR_SUCCESS;
	}
	catch (ELibMCDriver_ScannerEmulatorInterfaceException & Exception) {
		return handleLibMCDriver_ScannerEmulatorException(pIBaseClass, Exception);
	}
	catch (std::exception & StdException) {
		return handleStdException(pIBaseClass, StdException);
	}
	catch (...) {
		return handleUnhandledException(pIBaseClass);
	}
}


