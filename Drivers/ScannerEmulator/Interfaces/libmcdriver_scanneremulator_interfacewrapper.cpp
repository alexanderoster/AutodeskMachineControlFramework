LibMCDriver_ScannerEmulatorResult libmcdriver_scanneremulator_scanner_getname(LibMCDriver_ScannerEmulator_Scanner pScanner, const LibMCDriver_ScannerEmulator_uint32 nNameBufferSize, LibMCDriver_ScannerEmulator_uint32* pNameNeededChars, char * pNameBuffer)
{
	IBase* pIBaseClass = (IBase *)pScanner;

	try {
		if ( (!pNameBuffer) && !(pNameNeededChars) )
			throw ELibMCDriver_ScannerEmulatorInterfaceException (LIBMCDRIVER_SCANNEREMULATOR_ERROR_INVALIDPARAM);
		std::string sName("");
		IScanner* pIScanner = dynamic_cast<IScanner*>(pIBaseClass);
		if (!pIScanner)
			throw ELibMCDriver_ScannerEmulatorInterfaceException(LIBMCDRIVER_SCANNEREMULATOR_ERROR_INVALIDCAST);
		
		bool isCacheCall = (pNameBuffer == nullptr);
		if (isCacheCall) {
			sName = pIScanner->GetName();

			pIScanner->_setCache (new ParameterCache_1<std::string> (sName));
		}
		else {
			auto cache = dynamic_cast<ParameterCache_1<std::string>*> (pIScanner->_getCache ());
			if (cache == nullptr)
				throw ELibMCDriver_ScannerEmulatorInterfaceException(LIBMCDRIVER_SCANNEREMULATOR_ERROR_INVALIDCAST);
			cache->retrieveData (sName);
			pIScanner->_setCache (nullptr);
		}
		
		if (pNameNeededChars)
			*pNameNeededChars = (LibMCDriver_ScannerEmulator_uint32) (sName.size()+1);
		if (pNameBuffer) {
			if (sName.size() >= nNameBufferSize)
				throw ELibMCDriver_ScannerEmulatorInterfaceException (LIBMCDRIVER_SCANNEREMULATOR_ERROR_BUFFERTOOSMALL);
			for (size_t iName = 0; iName < sName.size(); iName++)
				pNameBuffer[iName] = sName[iName];
			pNameBuffer[sName.size()] = 0;
		}
		return LIBMCDRIVER_SCANNEREMULATOR_SUCCESS;
	}
	catch (ELibMCDriver_ScannerEmulatorInterfaceException & Exception) {
		return handleLibMCDriver_ScannerEmulatorException(pIBaseClass, Exception);
	}
	catch (std::exception & StdException) {
		return handleStdException(pIBaseClass, StdException);
	}
	catch (...) {
		return handleUnhandledException(pIBaseClass);
	}
}

