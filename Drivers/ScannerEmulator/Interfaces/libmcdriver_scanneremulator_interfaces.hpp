	virtual void AddSetDelays(const LibMCDriver_ScannerEmulator_double dLaserOnDelay, const LibMCDriver_ScannerEmulator_double dLaserOffDelay, const LibMCDriver_ScannerEmulator_double dJumpDelay, const LibMCDriver_ScannerEmulator_double dMarkDelay, const LibMCDriver_ScannerEmulator_double dPolygonDelay) = 0;

