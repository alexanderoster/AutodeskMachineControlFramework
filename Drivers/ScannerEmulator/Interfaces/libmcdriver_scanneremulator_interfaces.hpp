	virtual void AddEnableSkywriting(const LibMCDriver_ScannerEmulator::eSkywritingMode eMode, const LibMCDriver_ScannerEmulator_double dTimelag, const LibMCDriver_ScannerEmulator_double dLaserOnShift, const LibMCDriver_ScannerEmulator_double dNPrev, const LibMCDriver_ScannerEmulator_double dNPost, const LibMCDriver_ScannerEmulator_double dLimit) = 0;

